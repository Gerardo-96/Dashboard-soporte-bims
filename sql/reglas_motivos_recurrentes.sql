create table if not exists public.reglas_motivos_recurrentes (
    id bigint generated by default as identity primary key,
    palabras_clave text not null,
    motivo_recurrente text not null,
    prioridad integer not null default 100,
    activo boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint reglas_motivos_recurrentes_palabras_no_vacias
        check (length(trim(palabras_clave)) > 0),
    constraint reglas_motivos_recurrentes_motivo_no_vacio
        check (length(trim(motivo_recurrente)) > 0),
    constraint reglas_motivos_recurrentes_prioridad_positiva
        check (prioridad > 0)
);

create index if not exists idx_reglas_motivos_recurrentes_prioridad_activo
    on public.reglas_motivos_recurrentes (activo, prioridad, id);

-- Regla inicial solicitada: agrupar certificación, certificar, certificado y SIFEN.
insert into public.reglas_motivos_recurrentes
    (palabras_clave, motivo_recurrente, prioridad, activo)
select
    'certificación, certificar, certificado, SIFEN',
    'Certificación de comprobantes',
    10,
    true
where not exists (
    select 1
    from public.reglas_motivos_recurrentes
    where lower(trim(palabras_clave)) =
          lower('certificación, certificar, certificado, SIFEN')
      and lower(trim(motivo_recurrente)) =
          lower('Certificación de comprobantes')
);
